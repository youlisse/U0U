/* the audio ISR (dbx_audio.c): TIMER5 nests in it from the first line (USB waits for the end); its time, in thousandths of a half
 * buffer's, is averaged and its worst kept, and the help's third sheet shows both (dbx_ui.c DBX_CPU_LINE): the load, with the
 * scan and the USB that nest in it. To read on the FM-1 while it plays (M5: CPU). */
static struct { uint32_t t0, avg, max; } dbx_cpu;
#define DBX_HALF_TICKS ((HALF_FRAMES * 1000000u / FS) * FM1_TICKS_PER_US)
static __attribute__((noinline)) void dbx_cpu_leave(void)
{
    uint32_t pm = (fm1_ticks() - dbx_cpu.t0) * 1000u / DBX_HALF_TICKS;
    dbx_cpu.avg = (uint32_t)((int32_t)dbx_cpu.avg + ((int32_t)pm - (int32_t)dbx_cpu.avg) / 16);
    if (pm > dbx_cpu.max)
        dbx_cpu.max = pm;
    felucca_dbg.in_audio = 0;
}
static void dbx_cpu_line(char *b)                  /* "LOAD 23%  PEAK 41%" (the peak since it was last shown) */
{
    static const char *const W[2] = {"LOAD ", "  PEAK "};
    uint32_t v[2], i, k = 0, j;
    v[0] = dbx_cpu.avg / 10u;
    v[1] = dbx_cpu.max / 10u;
    dbx_cpu.max = 0;
    for (i = 0; i < 2u; i++) {
        for (j = 0; W[i][j]; j++)
            b[k++] = W[i][j];
        if (v[i] >= 100u)
            b[k++] = (char)('0' + v[i] / 100u % 10u);
        if (v[i] >= 10u)
            b[k++] = (char)('0' + v[i] / 10u % 10u);
        b[k++] = (char)('0' + v[i] % 10u);
        b[k++] = '%';
    }
    b[k] = 0;
}
#define DBX_CPU_LINE(b) dbx_cpu_line(b)
