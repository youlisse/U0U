# sample rate (44.1 kHz) instead of Peaks' 48 kHz, so that a note is the same pitch.
#   tools/gen_peaks.py   ->  firmware/src/dbx_peaks_tab.h
from pathlib import Path

import numpy as np

SR = 44100.0
OUT = Path(__file__).resolve().parent.parent / "firmware/src/dbx_peaks_tab.h"


def emit(name, ctype, vals, per=12):
    lines = [f"static const {ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
           "/* Generated by tools/gen_peaks.py (the tables of Mutable Instruments Peaks' drums, MIT, Emilie Gillet; at 44.1 kHz). Do not edit. */"]
    # SVF: cutoff by MIDI note and damping by resonance (a table of 257 entries each)
    cutoff = 440.0 * 2 ** ((np.arange(0, 257) - 69) / 12.0)
    f = cutoff / SR
    f[f > 1 / 8.0] = 1 / 8.0
    f = 2 * np.sin(np.pi * f)
    resonance = np.arange(0, 257) / 257.0
    damp = np.minimum(2 * (1 - resonance ** 0.25), np.minimum(2, 2 / f - f * 0.5))
    out.append(emit("PK_SVF_F", "int16_t", f * 32767.0))
    out.append(emit("PK_SVF_D", "uint16_t", damp * 32767.0))
    # the envelopes: the time of a decay (a gamma curve from 8 s to 0.5 ms), the exponential shape
    excursion = 1 << 32
    gamma = 0.175
    min_inc = excursion / (8.0 * SR)
    max_inc = excursion / (0.0005 * SR)
    rates = np.linspace(np.power(max_inc, -gamma), np.power(min_inc, -gamma), 257)
    out.append(emit("PK_ENV_INC", "uint32_t", np.power(rates, -1 / gamma).astype(np.int64), 8))
    env_linear = np.arange(0, 257.0) / 256.0
    env_linear[-1] = env_linear[-2]
    env_expo = 1.0 - np.exp(-4 * env_linear)
    out.append(emit("PK_ENV_EXPO", "uint16_t", env_expo / env_expo.max() * 65535.0))
    # the pitch of an oscillator: from the note 116 to 128 in steps of 1/8 semitone
    notes = np.arange(116 * 128.0, 128 * 128.0 + 16, 16)
    pitches = 440.0 * 2 ** ((notes - 69 * 128) / (128 * 12))
    out.append(emit("PK_OSC_INC", "uint32_t", (excursion / SR * pitches).astype(np.int64), 8))
    # a sine and the overdrive's shape (1025 points)
    x = np.arange(0, 1025) / 1024.0
    x[-1] = x[0]
    out.append(emit("PK_SINE", "int16_t", 32767 * np.sin(2 * np.pi * x), 16))
    x = np.arange(0, 1025) / 512.0 - 1.0
    x[-1] = x[-2]
    od = np.tanh(5.0 * x)
    od /= np.abs(od).max()
    out.append(emit("PK_OVERDRIVE", "int16_t", np.round(32767 * od), 16))
    OUT.write_text("\n".join(out) + "\n")
    print(f"gen_peaks: {OUT} ({OUT.stat().st_size} B)")


if __name__ == "__main__":
    main()
